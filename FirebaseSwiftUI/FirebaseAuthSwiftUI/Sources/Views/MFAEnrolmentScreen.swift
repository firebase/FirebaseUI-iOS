import FirebaseAuth
import FirebaseAuthUIComponents
import SwiftUI

/// The state and actions of the MFA enrolment screen, passed to ``MFAEnrolmentScreen``'s content.
public struct MFAEnrollmentContentState {
  /// A step of the enrolment flow.
  ///
  /// Later releases may add steps, so give a `switch` over it a `default` case.
  public enum Step {
    /// Choosing a factor, before ``MFAEnrollmentContentState/startEnrollment`` succeeds or once
    /// the enrolment session has expired or finished.
    case selectFactor
    /// Entering the phone number and display name for an SMS factor.
    case enterPhoneNumber
    /// Entering the code sent to ``MFAEnrollmentContentState/sentPhoneNumber``.
    case enterVerificationCode
    /// Adding ``MFAEnrollmentContentState/totpSecret`` to an authenticator app, then entering
    /// the display name and the code it generates.
    case setUpTOTP
  }

  /// The current step.
  public let step: Step

  /// The factor ``startEnrollment`` sets up. When the screen appears, it sets it to the first of
  /// ``allowedFactors`` if it is not one of them.
  public let selectedFactorType: Binding<SecondFactorType>

  /// The national phone number of an SMS factor, without the dial code.
  public let phoneNumber: Binding<String>

  /// The country whose dial code prefixes ``phoneNumber``.
  public let selectedCountry: Binding<CountryData>

  /// The code sent by SMS.
  public let verificationCode: Binding<String>

  /// The code generated by the authenticator app.
  public let totpCode: Binding<String>

  /// The name the factor is listed under.
  public let displayName: Binding<String>

  /// Starts enrolling ``selectedFactorType``, moving to ``Step/enterPhoneNumber`` or
  /// ``Step/setUpTOTP``. Does nothing unless ``step`` is ``Step/selectFactor``, ``isValid`` is
  /// `true` and ``isLoading`` is `false`.
  public let startEnrollment: @MainActor () -> Void

  /// Sends a code to the full phone number, moving to ``Step/enterVerificationCode``, or sends a
  /// new one from that step. Does nothing unless ``step`` is ``Step/enterPhoneNumber`` or
  /// ``Step/enterVerificationCode``, ``phoneNumber`` and ``displayName`` are non-empty, and
  /// ``isLoading`` is `false`.
  public let sendCode: @MainActor () -> Void

  /// Enrols the factor with the SMS or authenticator code, reauthenticating first when Firebase
  /// requires it, then clears navigation. Does nothing unless ``step`` is
  /// ``Step/enterVerificationCode`` or ``Step/setUpTOTP``, ``isValid`` is `true` and
  /// ``isLoading`` is `false`.
  public let enroll: @MainActor () -> Void

  /// Copies ``totpSecret`` to the pasteboard and sets ``didCopySecret`` briefly.
  public let copySecret: @MainActor () -> Void

  /// Whether MFA is enabled in the ``AuthConfiguration``.
  public let isMFAEnabled: Bool

  /// The factors the ``AuthConfiguration`` allows, SMS first.
  public let allowedFactors: [SecondFactorType]

  /// The number the code was sent to, including the dial code, from
  /// ``Step/enterVerificationCode``.
  public let sentPhoneNumber: String?

  /// The shared secret to enter in an authenticator app, from ``Step/setUpTOTP``.
  public let totpSecret: String?

  /// The `otpauth://` URL to show as a QR code or open in an authenticator app, from
  /// ``Step/setUpTOTP``.
  public let totpQRCodeURL: URL?

  /// Whether ``copySecret`` just copied the secret.
  public let didCopySecret: Bool

  /// Whether the current step's input is complete: MFA is enabled and ``selectedFactorType`` is
  /// one of ``allowedFactors`` in ``Step/selectFactor``, ``phoneNumber`` and ``displayName`` are
  /// non-empty in ``Step/enterPhoneNumber``, and ``displayName`` plus the step's code are
  /// non-empty in ``Step/enterVerificationCode`` and ``Step/setUpTOTP``.
  public let isValid: Bool

  /// Whether an enrolment action is in flight, or the ``AuthService`` is signing in.
  public let isLoading: Bool

  /// The localized message of the last failed action. It clears when any input changes or the
  /// next attempt starts. The sheet's error alert still shows for the same failure.
  public let errorMessage: String?

  /// Creates a state, for example to preview custom content with stub actions.
  public init(step: Step,
              selectedFactorType: Binding<SecondFactorType>,
              phoneNumber: Binding<String>,
              selectedCountry: Binding<CountryData>,
              verificationCode: Binding<String>,
              totpCode: Binding<String>,
              displayName: Binding<String>,
              startEnrollment: @escaping @MainActor () -> Void,
              sendCode: @escaping @MainActor () -> Void,
              enroll: @escaping @MainActor () -> Void,
              copySecret: @escaping @MainActor () -> Void,
              isMFAEnabled: Bool,
              allowedFactors: [SecondFactorType],
              sentPhoneNumber: String?,
              totpSecret: String?,
              totpQRCodeURL: URL?,
              didCopySecret: Bool,
              isValid: Bool,
              isLoading: Bool,
              errorMessage: String?) {
    self.step = step
    self.selectedFactorType = selectedFactorType
    self.phoneNumber = phoneNumber
    self.selectedCountry = selectedCountry
    self.verificationCode = verificationCode
    self.totpCode = totpCode
    self.displayName = displayName
    self.startEnrollment = startEnrollment
    self.sendCode = sendCode
    self.enroll = enroll
    self.copySecret = copySecret
    self.isMFAEnabled = isMFAEnabled
    self.allowedFactors = allowedFactors
    self.sentPhoneNumber = sentPhoneNumber
    self.totpSecret = totpSecret
    self.totpQRCodeURL = totpQRCodeURL
    self.didCopySecret = didCopySecret
    self.isValid = isValid
    self.isLoading = isLoading
    self.errorMessage = errorMessage
  }
}

/// The MFA enrolment screen, with its content drawn by you.
///
/// The screen starts the enrolment, sends SMS codes, enrols the factor, presents
/// reauthentication when Firebase requires it, and reports errors. Your content only draws the
/// UI for the ``MFAEnrollmentContentState/step`` it receives. Wrap ``DefaultMFAEnrolmentContent``
/// to keep the stock markup. The navigation title is part of that markup, so set your own on
/// custom content.
///
/// Example:
/// ```swift
/// AuthPickerView { authenticatedApp }
///   .pickerDestination { screen in
///     switch screen {
///     case .mfaEnrollment:
///       MFAEnrolmentScreen { state in
///         switch state.step {
///         case .enterPhoneNumber:
///           TextField("Phone number", text: state.phoneNumber)
///           TextField("Device name", text: state.displayName)
///           Button("Send code", action: state.sendCode)
///             .disabled(!state.isValid || state.isLoading)
///         default:
///           DefaultMFAEnrolmentContent(state: state)
///         }
///       }
///     default:
///       DefaultAuthPickerDestination(screen: screen)
///     }
///   }
/// ```
@MainActor
public struct MFAEnrolmentScreen<Content: View>: View {
  public init(@ViewBuilder content: @escaping (MFAEnrollmentContentState) -> Content) {
    self.content = content
  }

  @Environment(AuthService.self) private var authService
  @Environment(\.reportError) private var reportError
  @State private var selectedFactorType: SecondFactorType = .sms
  @State private var phoneNumber = ""
  @State private var selectedCountry: CountryData = .default
  @State private var verificationCode = ""
  @State private var totpCode = ""
  @State private var displayName = ""
  @State private var currentSession: EnrollmentSession?
  @State private var didCopySecret = false
  @State private var copyFeedback: Task<Void, Never>?
  @State private var isWorking = false
  @State private var errorMessage: String?
  @State private var reauthCoordinator = ReauthenticationCoordinator()

  private let content: (MFAEnrollmentContentState) -> Content

  public var body: some View {
    content(MFAEnrollmentContentState(
      step: step,
      selectedFactorType: $selectedFactorType,
      phoneNumber: $phoneNumber,
      selectedCountry: $selectedCountry,
      verificationCode: $verificationCode,
      totpCode: $totpCode,
      displayName: $displayName,
      startEnrollment: startEnrollment,
      sendCode: sendCode,
      enroll: enroll,
      copySecret: copySecret,
      isMFAEnabled: authService.configuration.mfaEnabled,
      allowedFactors: allowedFactors,
      sentPhoneNumber: currentSession?.phoneNumber,
      totpSecret: currentSession?.totpInfo?.sharedSecretKey,
      totpQRCodeURL: currentSession?.totpInfo?.qrCodeURL,
      didCopySecret: didCopySecret,
      isValid: isValid,
      isLoading: isLoading,
      errorMessage: errorMessage
    ))
    .withReauthentication(coordinator: reauthCoordinator)
    .onAppear {
      if !allowedFactors.contains(selectedFactorType),
         let firstAllowed = allowedFactors.first {
        selectedFactorType = firstAllowed
      }
    }
    .onChange(of: selectedFactorType) { errorMessage = nil }
    .onChange(of: phoneNumber) { errorMessage = nil }
    .onChange(of: selectedCountry) { errorMessage = nil }
    .onChange(of: verificationCode) { errorMessage = nil }
    .onChange(of: totpCode) { errorMessage = nil }
    .onChange(of: displayName) { errorMessage = nil }
  }

  private var allowedFactors: [SecondFactorType] {
    MFAEnrollmentContentState.sortedFactors(authService.configuration.allowedSecondFactors)
  }

  private var step: MFAEnrollmentContentState.Step {
    guard let session = currentSession else { return .selectFactor }
    return MFAEnrollmentContentState.Step(
      type: session.type,
      status: session.status,
      isExpired: session.isExpired
    )
  }

  private var isValid: Bool {
    step.isValid(
      isMFAEnabled: authService.configuration.mfaEnabled,
      allowedFactors: allowedFactors,
      selectedFactorType: selectedFactorType,
      phoneNumber: phoneNumber,
      verificationCode: verificationCode,
      totpCode: totpCode,
      displayName: displayName
    )
  }

  private var isLoading: Bool {
    isWorking || authService.authenticationState == .authenticating
  }

  private func startEnrollment() {
    guard step == .selectFactor, isValid, !isLoading else { return }
    isWorking = true
    errorMessage = nil
    Task {
      defer { isWorking = false }
      do {
        currentSession = try await authService.startMfaEnrollment(
          type: selectedFactorType,
          accountName: authService.currentUser?.email,
          issuer: authService.configuration.mfaIssuer
        )
      } catch {
        fail(error)
      }
    }
  }

  private func sendCode() {
    guard let session = currentSession,
          step == .enterPhoneNumber || step == .enterVerificationCode,
          !phoneNumber.isEmpty, !displayName.isEmpty, !isLoading else { return }
    isWorking = true
    errorMessage = nil
    Task {
      defer { isWorking = false }
      do {
        let fullPhoneNumber = selectedCountry.dialCode + phoneNumber
        let verificationId = try await authService.sendSmsVerificationForEnrollment(
          session: session,
          phoneNumber: fullPhoneNumber
        )
        currentSession = EnrollmentSession(
          id: session.id,
          type: session.type,
          session: session.session,
          totpInfo: session.totpInfo,
          phoneNumber: fullPhoneNumber,
          verificationId: verificationId,
          status: .verificationSent,
          createdAt: session.createdAt,
          expiresAt: session.expiresAt
        )
      } catch {
        fail(error)
      }
    }
  }

  private func enroll() {
    guard let session = currentSession,
          step == .enterVerificationCode || step == .setUpTOTP,
          isValid, !isLoading else { return }
    isWorking = true
    errorMessage = nil
    Task {
      defer { isWorking = false }
      do {
        let code = session.type == .sms ? verificationCode : totpCode
        try await withReauthenticationIfNeeded(
          authService: authService,
          coordinator: reauthCoordinator
        ) {
          try await authService.completeEnrollment(
            session: session,
            verificationId: session.verificationId,
            verificationCode: code,
            displayName: displayName
          )
        }
        resetForm()
        authService.navigator.clear()
      } catch {
        fail(error)
      }
    }
  }

  private func copySecret() {
    guard let secret = currentSession?.totpInfo?.sharedSecretKey else { return }
    UIPasteboard.general.string = secret
    didCopySecret = true
    copyFeedback?.cancel()
    copyFeedback = Task {
      try? await Task.sleep(nanoseconds: 500_000_000)
      guard !Task.isCancelled else { return }
      didCopySecret = false
    }
  }

  private func fail(_ error: Error) {
    errorMessage = authService.string.localizedErrorMessage(for: error)
    reportError?(error)
  }

  private func resetForm() {
    currentSession = nil
    phoneNumber = ""
    selectedCountry = .default
    verificationCode = ""
    totpCode = ""
    displayName = ""
  }
}

extension MFAEnrollmentContentState {
  /// The factors in display order, SMS first.
  static func sortedFactors(_ factors: Set<SecondFactorType>) -> [SecondFactorType] {
    factors.sorted { lhs, rhs in lhs == .sms && rhs == .totp }
  }
}

extension MFAEnrollmentContentState.Step {
  /// The step for a started enrolment session. Sessions that have expired or finished go back to
  /// ``selectFactor`` so the user can start again.
  init(type: SecondFactorType, status: EnrollmentSession.EnrollmentStatus, isExpired: Bool) {
    switch (type, status) {
    case _ where isExpired, (_, .completed), (_, .failed), (_, .expired):
      self = .selectFactor
    case (.sms, .initiated):
      self = .enterPhoneNumber
    case (.sms, .verificationSent), (.sms, .verificationPending):
      self = .enterVerificationCode
    case (.totp, _):
      self = .setUpTOTP
    }
  }

  /// Whether the input this step needs is complete.
  func isValid(isMFAEnabled: Bool,
               allowedFactors: [SecondFactorType],
               selectedFactorType: SecondFactorType,
               phoneNumber: String,
               verificationCode: String,
               totpCode: String,
               displayName: String) -> Bool {
    switch self {
    case .selectFactor:
      isMFAEnabled && allowedFactors.contains(selectedFactorType)
    case .enterPhoneNumber:
      !phoneNumber.isEmpty && !displayName.isEmpty
    case .enterVerificationCode:
      !verificationCode.isEmpty && !displayName.isEmpty
    case .setUpTOTP:
      !totpCode.isEmpty && !displayName.isEmpty
    }
  }
}
